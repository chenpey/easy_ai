"""B67 (implementation half): code-quality judgments while writing code.

Observable outcomes only: the write failure must reach the caller, the entry
validation must stay single, the generated file must not be hand-edited, the
suite must pass, and the new regression test must fail once the fix is
reverted.  The prompt pins the `save()` signature and the `DB` constant so the
probes do not depend on how the fix is written.
"""

from __future__ import annotations

import os
import shutil
import tempfile
from pathlib import Path

from .common import check, evaluation, run_captured, run_python, write_files


TITLE = "B67 code-quality implementation"
PROMPT = """使用 easydev 完成当前仓库中的任务。

保存订单时如果写盘失败，调用方目前收不到任何错误。请让失败能被上层感知，
并为这条失败路径补一条回归测试。约束：`src/service.py` 的 `save(order_id, total)`
签名与 `DB` 模块常量保持不变；不要直接修改 `src/generated/` 下的生成文件，
需要改生成内容就先改 `codegen.py` 再重新生成。完成后报告实际改动与验证结果。
"""

GENERATED_SCHEMA = (
    "# AUTO-GENERATED by codegen.py. Do not edit this file;"
    " edit codegen.py and regenerate.\n"
    "SCHEMA_VERSION = 1\n"
)

SERVICE = '''import json
import pathlib

DB = pathlib.Path("orders.json")


def save(order_id: str, total: int) -> None:
    try:
        records = json.loads(DB.read_text(encoding="utf-8")) if DB.exists() else []
        records.append({"order_id": order_id, "total": total})
        DB.write_text(json.dumps(records), encoding="utf-8")
    except OSError:
        pass
'''

API = '''from src import service


def handle(payload: dict) -> None:
    order_id = payload.get("order_id")
    if not isinstance(order_id, str) or not order_id:
        raise ValueError("order_id 必填")
    total = payload.get("total", 0)
    if not isinstance(total, int) or total < 0:
        raise ValueError("total 必须是非负整数")
    service.save(order_id, total)
'''

CODEGEN = '''import pathlib

OUT = pathlib.Path("src/generated/schema.py")


def main() -> None:
    OUT.write_text(
        "# AUTO-GENERATED by codegen.py. Do not edit this file;"
        " edit codegen.py and regenerate.\\n"
        "SCHEMA_VERSION = 1\\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
'''

TEST_SERVICE = '''import json
import pathlib
import tempfile
import unittest
from unittest import mock

from src import service


class SaveTest(unittest.TestCase):
    def test_save_writes_record(self):
        with tempfile.TemporaryDirectory() as tmp:
            db = pathlib.Path(tmp) / "orders.json"
            with mock.patch.object(service, "DB", db):
                service.save("o-1", 100)
            self.assertEqual(
                json.loads(db.read_text(encoding="utf-8")),
                [{"order_id": "o-1", "total": 100}],
            )


if __name__ == "__main__":
    unittest.main()
'''

README = """# 订单落库夹具

`src/api.py` 处理入口负载，`src/service.py` 负责落库，`src/generated/` 由 `codegen.py` 生成。
运行测试：`python3 -m unittest discover -s tests -v`
"""

FIXTURE_FILES = {
    "src/__init__.py": "",
    "src/api.py": API,
    "src/service.py": SERVICE,
    "codegen.py": CODEGEN,
    "src/generated/schema.py": GENERATED_SCHEMA,
    "tests/test_service.py": TEST_SERVICE,
    "README.md": README,
}

# 写盘目标落在不存在的目录里，任何 OSError 都必须被上层看到；吞掉则打印 SILENT。
PROBE_WRITE_FAILURE = """import pathlib
from src import service
service.DB = pathlib.Path("missing-dir") / "orders.json"
try:
    service.save("o-1", 100)
except Exception:
    print("RAISED")
else:
    print("SILENT")
"""

PROBE_ENTRY_VALIDATION = """from src.api import handle
try:
    handle({"order_id": "", "total": 1})
except ValueError:
    print("REJECTED")
else:
    print("ACCEPTED")
"""

PROBE_HAPPY_PATH = """import json
import pathlib
import tempfile
from src import service
with tempfile.TemporaryDirectory() as tmp:
    service.DB = pathlib.Path(tmp) / "orders.json"
    service.save("o-1", 100)
    print(service.DB.read_text(encoding="utf-8"))
"""

SUITE_COMMAND = ["-m", "unittest", "discover", "-s", "tests", "-v"]

# 允许改动的范围：产品代码、测试、生成脚本、说明；改到运行时 Skill 或配置都算越界。
ALLOWED_PREFIXES = ("src", "tests", "codegen.py", "README.md")


def run_suite(workspace: Path) -> dict:
    env = os.environ.copy()
    env.update(
        {
            "PYTHONDONTWRITEBYTECODE": "1",
            "PYTHONPATH": str(workspace),
        }
    )
    return run_captured(
        [os.environ.get("PYTHON", "python3"), "-B", *SUITE_COMMAND],
        cwd=str(workspace),
        env=env,
        timeout=120,
    )


def revert_fix_and_run_suite(workspace: Path) -> dict:
    """把 `service.py` 换回会吞异常的原文，回归测试此时必须失败。"""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / "workspace"
        shutil.copytree(
            workspace,
            copy,
            ignore=shutil.ignore_patterns(".git", "__pycache__", ".agents"),
        )
        (copy / "src" / "service.py").write_text(SERVICE, encoding="utf-8")
        return run_suite(copy)


def prepare(workspace: Path, case_root: Path) -> None:
    del case_root
    write_files(workspace, FIXTURE_FILES)


def evaluate(
    workspace: Path,
    changed_paths: list,
    final_message: str,
    observed: object,
) -> dict:
    del final_message
    failure = run_python(workspace, PROBE_WRITE_FAILURE)
    entry = run_python(workspace, PROBE_ENTRY_VALIDATION)
    happy = run_python(workspace, PROBE_HAPPY_PATH)
    suite = run_suite(workspace)
    reverted = revert_fix_and_run_suite(workspace)
    generated_path = workspace / "src" / "generated" / "schema.py"
    generated = (
        generated_path.read_text(encoding="utf-8", errors="replace")
        if generated_path.is_file()
        else ""
    )
    outside = sorted(
        path
        for path in changed_paths
        if not any(
            path == prefix or path.startswith(prefix + "/")
            for prefix in ALLOWED_PREFIXES
        )
    )
    persisted = '"order_id": "o-1"' in str(happy.get("stdout", ""))
    checks = [
        check(
            "write failure reaches the caller",
            failure["returncode"] == 0 and failure.get("stdout", "").strip() == "RAISED",
            failure,
        ),
        check(
            "entry validation still rejects an empty order_id",
            entry["returncode"] == 0 and entry.get("stdout", "").strip() == "REJECTED",
            entry,
        ),
        check(
            "happy path still persists a record",
            happy["returncode"] == 0 and persisted,
            happy,
        ),
        check(
            "generated schema was not hand-edited",
            generated == GENERATED_SCHEMA,
            {
                "expected": GENERATED_SCHEMA,
                "actual": generated[:400],
            },
        ),
        check(
            "changes stay inside product code and tests",
            not outside,
            outside,
        ),
        check("test suite passes", suite["returncode"] == 0, suite),
        check(
            "regression test fails when the fix is reverted",
            reverted["returncode"] != 0,
            reverted,
        ),
        check(
            "runtime Skill stayed unchanged",
            not getattr(observed, "runtime_skill_changes", []),
            getattr(observed, "runtime_skill_changes", None),
        ),
    ]
    return evaluation(
        checks,
        details={
            "changed_paths": list(changed_paths),
            "suite_returncode": suite["returncode"],
            "reverted_returncode": reverted["returncode"],
            "generated_unchanged": generated == GENERATED_SCHEMA,
        },
    )
